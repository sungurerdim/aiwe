// TestArchive catches an archive that is not newest first or that drops a close reason.
func TestArchive(t *testing.T) {
	w := newWorld()
	res, err := generate(context.Background(), w.toolDeps(stamp()), "archive")
	if err != nil {
		t.Fatalf("generate archive: %v", err)
	}
	want := "# ARCHIVE\n\n" +
		"4 closed issues, newest first. Regenerate: `go run ./internal/cmd/records --write archive`\n\n" +
		"- 2026-10-24 · #399 Tool wrapper · not planned\n" +
		"- 2026-10-24 · #5 First report · completed\n" +
		"- 2026-10-20 · #458 Item lint · completed\n" +
		"- 2026-10-01 · #3 Odd close · unknown\n"
	if got := withoutStamp(body(t, res.recs, "ARCHIVE.md")); got != want {
		t.Errorf("ARCHIVE.md =\n%s\nwant\n%s", got, want)
	}
}

// TestDecisions catches an index that reads rows outside the §16 table, loses a row, or does not
// cut the decision text at 120 characters.
func TestDecisions(t *testing.T) {
	w := newWorld()
	res, err := generate(context.Background(), w.toolDeps(stamp()), "decisions")
	if err != nil {
		t.Fatalf("generate decisions: %v", err)
	}
	long := "Record files are not committed: TODO.md, ARCHIVE.md and DECISIONS.md are generated by the item " +
		"commands and the decision log, and the only hand-kept text is the broken list (owner, 2026-10-25)."
	want := "# DECISIONS\n\n" +
		"3 decisions. Full text: [docs/SPEC.md](docs/SPEC.md#16-decision-log). " +
		"Regenerate: `go run ./internal/cmd/records --write decisions`\n\n" +
		"- O1 · superseded in part by L58 · Walking skeleton first (owner, 2026-10-12).\n" +
		"- O4 · valid · Operation units are deferred (§15) (owner, 2026-10-12).\n" +
		"- L41 · valid · " + strings.TrimRight(long[:120], " ") + "...\n"
	got := body(t, res.recs, "DECISIONS.md")
	if text := withoutStamp(got); text != want {
		t.Errorf("DECISIONS.md =\n%s\nwant\n%s", text, want)
	}
	if first := strings.SplitN(got, "\n", 2)[0]; !strings.Contains(first, "from docs/SPEC.md §16") {
		t.Errorf("first line %q does not name its source", first)
	}
}

// TestFailClosed catches a run that writes any file, or exits 0, when one input cannot be read; the
// one error line must name what failed.
func TestFailClosed(t *testing.T) {
	cases := []struct {
		name string
		key  string
		want string
	}{
		{"gh not logged in", "gh auth status", "gh auth status"},
		{"open issues unreadable", "issue list --state open", "gh issue list"},
		{"closed issues unreadable", "issue list --state closed", "gh issue list"},
		{"sub-issues unreadable", "/sub_issues", "gh api"},
		{"CI run unreadable", "gh run list", "gh run list"},
		{"git unreadable", "git rev-parse HEAD", "git rev-parse"},
		{"SPEC missing", "", "docs/SPEC.md"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			w := newWorld()
			if tc.key == "" {
				delete(w.files, "docs/SPEC.md")
			} else {
				w.fail[tc.key] = errors.New("boom: " + tc.key)
			}
			var written []string
			var out, errw bytes.Buffer
			code := execute(context.Background(), []string{"--write", "all"}, w.toolDeps(stamp()),
				func(r record) error { written = append(written, r.name); return nil }, &out, &errw)
			if code == 0 {
				t.Errorf("exit code = 0, want non-zero")
			}
			if len(written) != 0 {
				t.Errorf("wrote %v after a failure, want nothing", written)
			}
			line := strings.TrimRight(errw.String(), "\n")
			if strings.Contains(line, "\n") || !strings.HasPrefix(line, "records: ") || !strings.Contains(line, tc.want) {
				t.Errorf("stderr = %q, want one line `records: ... %s ...`", errw.String(), tc.want)
			}
		})
	}
}

// TestIdempotent catches a generation that drifts between two runs over the same input.
func TestIdempotent(t *testing.T) {
	run := func(w *fakeWorld, at time.Time) map[string]string {
		res, err := generate(context.Background(), w.toolDeps(at), "all")
		if err != nil {
			t.Fatalf("generate all: %v", err)
		}
		got := map[string]string{}
		for _, r := range res.recs {
			got[r.name] = string(r.body)
		}
		return got
	}
	w := newWorld()
	first := run(w, stamp())
	if len(first) != 4 {
		t.Fatalf("all produced %d records, want 4", len(first))
	}
	w.files["STATUS.md"] = first["STATUS.md"]
	same := run(w, stamp())
	later := run(w, stamp().Add(26*time.Hour))
	for name, text := range first {
		if same[name] != text {
			t.Errorf("%s differs between two runs at the same time", name)
		}
		if withoutStamp(later[name]) != withoutStamp(text) {
			t.Errorf("%s differs beyond the stamp line between two runs", name)
		}
		if later[name] == text {
			t.Errorf("%s carries no time stamp", name)
		}
	}
}

// TestExecute catches a dry run that writes, a write that skips a record, and a bad command line.
func TestExecute(t *testing.T) {
	t.Run("a dry run prints every record and writes none", func(t *testing.T) {
		w := newWorld()
		var written []string
		var out, errw bytes.Buffer
		code := execute(context.Background(), []string{"all"}, w.toolDeps(stamp()),
			func(r record) error { written = append(written, r.name); return nil }, &out, &errw)
		if code != 0 || len(written) != 0 || errw.Len() != 0 {
			t.Errorf("code=%d written=%v stderr=%q, want a silent dry run", code, written, errw.String())
		}
		for _, name := range []string{"TODO.md", "ARCHIVE.md", "DECISIONS.md", "STATUS.md"} {
			if !strings.Contains(out.String(), "==> "+name+" <==") {
				t.Errorf("dry run does not print %s", name)
			}
		}
	})

	t.Run("--write writes the four records in order", func(t *testing.T) {
		w := newWorld()
		var written []string
		var out, errw bytes.Buffer
		code := execute(context.Background(), []string{"--write", "all"}, w.toolDeps(stamp()),
			func(r record) error { written = append(written, r.name); return nil }, &out, &errw)
		if got := strings.Join(written, ","); code != 0 || got != "TODO.md,ARCHIVE.md,DECISIONS.md,STATUS.md" {
			t.Errorf("code=%d written=%s stderr=%q", code, got, errw.String())
		}
	})

	t.Run("a bad command line is a usage error with one line", func(t *testing.T) {
		for _, args := range [][]string{nil, {"nonsense"}, {"todo", "status"}, {"--bogus", "todo"}} {
			w := newWorld()
			var out, errw bytes.Buffer
			code := execute(context.Background(), args, w.toolDeps(stamp()),
				func(record) error { t.Errorf("wrote on a usage error"); return nil }, &out, &errw)
			line := strings.TrimRight(errw.String(), "\n")
			if code != 2 || strings.Contains(line, "\n") || !strings.HasPrefix(line, "records: ") {
				t.Errorf("args %v: code=%d stderr=%q, want exit 2 and one records: line", args, code, errw.String())
			}
		}
	})
}
