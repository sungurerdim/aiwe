// A fake world: the answers of gh and git for a small tracker, with the shapes the real tools
// print after their own --json / --jq handling. No test touches the network or a repository.

var issueNumber = regexp.MustCompile(`issues/([0-9]+)/`)

// withLinks returns an issue body that carries the JSON record block with links.blockedBy.
func withLinks(blockedBy ...int) string {
	rec, _ := json.Marshal(map[string]any{"v": 1, "kind": "unit", "links": map[string]any{"blockedBy": blockedBy}})
	return "## Item\n\n```json\n" + string(rec) + "\n```\n"
}

// fakeWorld answers every call the tool makes; a key of fail that the command contains makes it fail.
type fakeWorld struct {
	mu     sync.Mutex
	calls  []string
	open   []issue
	closed []issue
	subs   map[int][]int
	deps   map[int][]int
	depErr map[int]bool
	fail   map[string]error
	files  map[string]string
}

func (w *fakeWorld) run(_ context.Context, name string, args ...string) ([]byte, error) {
	cmd := name + " " + strings.Join(args, " ")
	w.mu.Lock()
	w.calls = append(w.calls, cmd)
	w.mu.Unlock()
	for key, err := range w.fail {
		if strings.Contains(cmd, key) {
			return nil, err
		}
	}
	num := 0
	if m := issueNumber.FindStringSubmatch(cmd); m != nil {
		_, _ = fmt.Sscan(m[1], &num)
	}
	switch {
	case strings.HasPrefix(cmd, "gh auth status"):
		return []byte("Logged in\n"), nil
	case strings.HasPrefix(cmd, "gh issue list") && strings.Contains(cmd, "--state open"):
		return json.Marshal(w.open)
	case strings.HasPrefix(cmd, "gh issue list") && strings.Contains(cmd, "--state closed"):
		return json.Marshal(w.closed)
	case strings.Contains(cmd, "/sub_issues"):
		return numberLines(w.subs[num]), nil
	case strings.Contains(cmd, "/dependencies/blocked_by"):
		if w.depErr[num] {
			return nil, errors.New("gh: HTTP 404 Not Found")
		}
		return numberLines(w.deps[num]), nil
	case strings.HasPrefix(cmd, "gh run list"):
		return []byte(`[{"conclusion":"failure","status":"completed","workflowName":"ci",` +
			`"createdAt":"2026-10-24T08:02:31Z","headSha":"527ba9aa3105452f9c96c53ededf59dc2b521416"}]`), nil
	case cmd == "git rev-parse HEAD":
		return []byte("e1bb4291f0a3c5d6e7f8091a2b3c4d5e6f708192\n"), nil
	case cmd == "git log -1 --format=%s":
		return []byte("docs: make the SPEC provider-agnostic\n"), nil
	case cmd == "git rev-parse --abbrev-ref HEAD":
		return []byte("main\n"), nil
	case strings.HasPrefix(cmd, "git rev-list --left-right --count"):
		return []byte("1\t2\n"), nil
	}
	return nil, fmt.Errorf("fake world: unexpected command %q", cmd)
}

func numberLines(nums []int) []byte {
	var b strings.Builder
	for _, n := range nums {
		fmt.Fprintf(&b, "%d\n", n)
	}
	return []byte(b.String())
}

// read serves the repository files of the fake world.
func (w *fakeWorld) read(name string) ([]byte, bool, error) {
	body, ok := w.files[name]
	return []byte(body), ok, nil
}

// deps returns the tool dependencies over this world at the given time.
func (w *fakeWorld) toolDeps(at time.Time) deps {
	return deps{run: w.run, read: w.read, now: func() time.Time { return at }}
}

