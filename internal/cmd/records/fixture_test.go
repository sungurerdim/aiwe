// body returns the record named name from a generation result.
func body(t *testing.T, recs []record, name string) string {
	t.Helper()
	for _, r := range recs {
		if r.name == name {
			return string(r.body)
		}
	}
	t.Fatalf("no record %s in %d records", name, len(recs))
	return ""
}

// withoutStamp drops the generated marker line, the one line that may differ between runs.
func withoutStamp(text string) string {
	var kept []string
	for _, line := range strings.Split(text, "\n") {
		if !strings.HasPrefix(line, "<!-- generated ") {
			kept = append(kept, line)
		}
	}
	return strings.Join(kept, "\n")
}
